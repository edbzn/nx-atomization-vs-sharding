// File templates for the workspace-size scaling experiment (generator/scale.mjs).
//
// Every lib is a small TypeScript library of pure functions with Vitest specs in the node
// environment. Spec runtime is a deterministic integer fold (Math.imul loop) whose expected
// result is computed by the generator with the same arithmetic (see foldJs / stepJs), so
// every assertion is real and every spec passes.

import { PNPM_VERSION } from '../templates/root.mjs';

export const SCALE_VERSIONS = {
  nx: '23.3.0',
  vitest: '4.1.11',
  vite: '7.3.7',
  typescript: '5.9.3',
  typesNode: '24.19.1',
  swcNodeRegister: '1.12.1',
  swcCore: '1.16.13',
  tslib: '2.8.1',
};

export const IMPORT_SCOPE = '@scale';

const json = (o) => JSON.stringify(o, null, 2) + '\n';
const hex = (n) => `0x${(n >>> 0).toString(16).padStart(8, '0')}`;
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

// ------------------------------------------------------------------ arithmetic (mirrors the TS)
const STEP_MUL_A = 0x85ebca6b;
const STEP_MUL_B = 0xc2b2ae35;

/** JS twin of core.ts `step`. */
export function stepJs(salt, x) {
  let h = Math.imul((x ^ salt) >>> 0, STEP_MUL_A) >>> 0;
  h ^= h >>> 13;
  return Math.imul(h, STEP_MUL_B) >>> 0;
}

/** JS twin of `<mod>Fold`: `start` = (step(seed) ^ depStep(seed) ^ ...) >>> 0. */
export function foldJs(start, rounds, multiplier) {
  let h = start >>> 0;
  for (let i = 0; i < rounds; i++) h = Math.imul(h ^ (h >>> 15) ^ i, multiplier) >>> 0;
  return h;
}

export const labelJs = (mod, value) => `${mod}-${(value >>> 0).toString(16).padStart(8, '0')}`;

