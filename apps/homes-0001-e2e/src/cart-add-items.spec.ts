import { expect, test } from '@playwright/test';

test('adds 2 listings to the cart and updates totals', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Homes Finder');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: 'Listings' }).click();
  await page.getByRole('searchbox', { name: 'Filter' }).fill('LST-0020');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await page.getByTestId('row').first().click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Central Villa');
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await expect(page.getByTestId('quantity')).toHaveText('4');
  await page.getByRole('button', { name: 'Add to cart' }).click();
  await expect(page.getByRole('status').last()).toHaveText('Added 4 × Central Villa');
  await expect(page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ })).toHaveText('Cart (4)');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: 'Listings' }).click();
  await page.getByRole('searchbox', { name: 'Filter' }).fill('LST-0038');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await page.getByTestId('row').first().click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Corner Townhouse');
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await expect(page.getByTestId('quantity')).toHaveText('5');
  await page.getByRole('button', { name: 'Add to cart' }).click();
  await expect(page.getByRole('status').last()).toHaveText('Added 5 × Corner Townhouse');
  await expect(page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ })).toHaveText('Cart (9)');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ }).click();
  await expect(page.getByTestId('cart-line')).toHaveCount(2);
  await expect(page.getByTestId('line-quantity').nth(0)).toHaveText('4');
  await expect(page.getByTestId('line-total').nth(0)).toHaveText('$10,951.76');
  await expect(page.getByTestId('line-quantity').nth(1)).toHaveText('5');
  await expect(page.getByTestId('line-total').nth(1)).toHaveText('$2,647.05');
  await expect(page.getByTestId('cart-subtotal')).toHaveText('Subtotal: $13,598.81');
  await page.getByRole('button', { name: 'Remove LST-0038' }).click();
  await expect(page.getByTestId('cart-line')).toHaveCount(1);
  await expect(page.getByTestId('line-quantity').nth(0)).toHaveText('4');
  await expect(page.getByTestId('line-total').nth(0)).toHaveText('$10,951.76');
  await expect(page.getByTestId('cart-subtotal')).toHaveText('Subtotal: $10,951.76');
});

