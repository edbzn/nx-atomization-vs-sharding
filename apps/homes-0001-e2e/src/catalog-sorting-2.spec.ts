import { expect, test } from '@playwright/test';

test('filters, sorts and pages the listings catalog (8 steps)', async ({ page }) => {
  await page.goto('/catalog');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Listings');
  const filter = page.getByRole('searchbox', { name: 'Filter' });
  await page.getByRole('button', { name: 'Next' }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 11-20 of 96');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('LST-0011');
  await filter.clear();
  await filter.pressSequentially('flat');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-7 of 7');
  await expect(page.getByTestId('row')).toHaveCount(7);
  await filter.clear();
  await filter.pressSequentially('LST-0077');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-1 of 1');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await filter.clear();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 96');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('LST-0001');
  await page.getByRole('button', { name: 'Next' }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 11-20 of 96');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('LST-0011');
  await page.getByRole('button', { name: /^Name/ }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 96');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('LST-0047');
  await page.getByRole('button', { name: /^Reference/ }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 96');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('LST-0001');
  await filter.fill('town');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-7 of 7');
  await expect(page.getByTestId('row')).toHaveCount(7);
});

