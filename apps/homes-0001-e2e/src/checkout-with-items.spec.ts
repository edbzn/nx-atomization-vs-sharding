import { expect, test } from '@playwright/test';

test('validates the checkout form and places an order with items (9 edits)', async ({ page }) => {
  await page.goto('/catalog');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: 'Listings' }).click();
  await page.getByRole('searchbox', { name: 'Filter' }).fill('LST-0062');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await page.getByTestId('row').first().click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Furnished Terrace');
  await expect(page.getByTestId('quantity')).toHaveText('1');
  await page.getByRole('button', { name: 'Add to cart' }).click();
  await expect(page.getByRole('status').last()).toHaveText('Added 1 × Furnished Terrace');
  await expect(page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ })).toHaveText('Cart (1)');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ }).click();
  await page.getByRole('link', { name: 'Proceed to checkout' }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Checkout');
  await page.getByRole('button', { name: 'Place order' }).click();
  await expect(page.getByTestId('error-summary')).toHaveText('7 errors');
  await expect(page.getByRole('alert')).toHaveCount(7);
  await page.getByRole('textbox', { name: 'Address', exact: true }).clear();
  await page.getByRole('textbox', { name: 'Address', exact: true }).pressSequentially('Juniperstraat 62');
  await expect(page.getByRole('textbox', { name: 'Address', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Postal code', exact: true }).clear();
  await page.getByRole('textbox', { name: 'Postal code', exact: true }).pressSequentially('7547');
  await expect(page.getByRole('textbox', { name: 'Postal code', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Address', exact: true }).fill('Rd');
  await expect(page.getByRole('textbox', { name: 'Address', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Address', exact: true }).fill('Onyxstraat 168');
  await expect(page.getByRole('textbox', { name: 'Address', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'City', exact: true }).clear();
  await page.getByRole('textbox', { name: 'City', exact: true }).pressSequentially('Mechelen');
  await expect(page.getByRole('textbox', { name: 'City', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Full name', exact: true }).fill('Wout Bogaert');
  await expect(page.getByRole('textbox', { name: 'Full name', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Postal code', exact: true }).fill('7439');
  await expect(page.getByRole('textbox', { name: 'Postal code', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Address', exact: true }).fill('Riverstraat 84');
  await expect(page.getByRole('textbox', { name: 'Address', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Postal code', exact: true }).fill('90');
  await expect(page.getByRole('textbox', { name: 'Postal code', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Email', exact: true }).fill('victor.van.damme81@example.com');
  await expect(page.getByRole('textbox', { name: 'Email', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Postal code', exact: true }).fill('2970');
  await expect(page.getByRole('textbox', { name: 'Postal code', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('combobox', { name: 'Delivery' }).selectOption('Standard');
  await page.getByRole('checkbox', { name: 'I accept the terms' }).check();
  await page.getByRole('button', { name: 'Place order' }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Thank you, Wout Bogaert');
  await expect(page.getByTestId('order-reference')).toHaveText('REF-0724E5C');
  await expect(page.getByTestId('order-total')).toHaveText('1 item · $2,310.66');
});

