import { expect, test } from '@playwright/test';

test('filters, sorts and pages the listings catalog (8 steps)', async ({ page }) => {
  await page.goto('/catalog');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Listings');
  const filter = page.getByRole('searchbox', { name: 'Filter' });
  await filter.fill('lst-000');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-9 of 9');
  await expect(page.getByTestId('row')).toHaveCount(9);
  await filter.fill('studio');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 19');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await page.getByRole('button', { name: /^Name/ }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 19');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('LST-0085');
  await page.getByRole('button', { name: 'Next' }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 11-19 of 19');
  await expect(page.getByTestId('row')).toHaveCount(9);
  await expect(page.getByTestId('row').first()).toContainText('LST-0003');
  await filter.clear();
  await filter.pressSequentially('Cor');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 12');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await page.getByRole('button', { name: /^Price/ }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 12');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('LST-0038');
  await page.getByRole('button', { name: 'Next' }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 11-12 of 12');
  await expect(page.getByTestId('row')).toHaveCount(2);
  await expect(page.getByTestId('row').first()).toContainText('LST-0090');
  await page.getByRole('button', { name: /^Price/ }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 12');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('LST-0037');
  await page.getByTestId('row').filter({ hasText: 'LST-0037' }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Corner Suite');
  await expect(page.getByTestId('detail-price')).toHaveText('$9,932.28');
});

