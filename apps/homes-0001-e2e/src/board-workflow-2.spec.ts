import { expect, test } from '@playwright/test';

test('plans work on the board and keeps it after a reload (10 steps)', async ({ page }) => {
  await page.goto('/board');
  const newCard = page.getByRole('textbox', { name: 'New card' });
  const filter = page.getByRole('searchbox', { name: 'Filter cards' });
  const cardsIn = (column: string) => page.getByRole('region', { name: column }).getByTestId('card');
  await newCard.fill('Quote bungalow comet');
  await newCard.press('Enter');
  await newCard.fill('Call villa alpha');
  await newCard.press('Enter');
  await expect(cardsIn('To do')).toHaveCount(2);
  await expect(cardsIn('In progress')).toHaveCount(0);
  await expect(cardsIn('Done')).toHaveCount(0);
  await expect(page.getByTestId('board-summary')).toHaveText('0 of 2 done');
  await page.getByRole('button', { name: 'Delete Quote bungalow comet' }).click();
  await newCard.fill('Restock flat lark');
  await newCard.press('Enter');
  await expect(cardsIn('To do')).toHaveCount(2);
  await expect(cardsIn('In progress')).toHaveCount(0);
  await expect(cardsIn('Done')).toHaveCount(0);
  await expect(page.getByTestId('board-summary')).toHaveText('0 of 2 done');
  await filter.fill('Rest');
  await newCard.pressSequentially('Quote townhouse falcon');
  await newCard.press('Enter');
  await expect(cardsIn('To do')).toHaveCount(1);
  await expect(cardsIn('In progress')).toHaveCount(0);
  await expect(cardsIn('Done')).toHaveCount(0);
  await expect(page.getByTestId('board-summary')).toHaveText('0 of 3 done');
  await filter.clear();
  await filter.fill('lark');
  await expect(cardsIn('To do')).toHaveCount(1);
  await expect(cardsIn('In progress')).toHaveCount(0);
  await expect(cardsIn('Done')).toHaveCount(0);
  await expect(page.getByTestId('board-summary')).toHaveText('0 of 3 done');
  await newCard.fill('Call penthouse pine');
  await newCard.press('Enter');
  await page.getByRole('button', { name: 'Delete Restock flat lark' }).click();
  await expect(cardsIn('To do')).toHaveCount(0);
  await expect(cardsIn('In progress')).toHaveCount(0);
  await expect(cardsIn('Done')).toHaveCount(0);
  await expect(page.getByTestId('board-summary')).toHaveText('0 of 3 done');
  await page.reload();
  await expect(cardsIn('To do')).toHaveCount(3);
  await expect(cardsIn('In progress')).toHaveCount(0);
  await expect(cardsIn('Done')).toHaveCount(0);
  await expect(page.getByTestId('board-summary')).toHaveText('0 of 3 done');
});

