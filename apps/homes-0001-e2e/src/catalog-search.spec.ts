import { expect, test } from '@playwright/test';

test('filters, sorts and pages the listings catalog (4 steps)', async ({ page }) => {
  await page.goto('/catalog');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Listings');
  const filter = page.getByRole('searchbox', { name: 'Filter' });
  await filter.fill('apartment');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 14');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await page.getByRole('button', { name: /^Price/ }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 14');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('LST-0038');
  await page.getByRole('button', { name: /^Name/ }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 14');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('LST-0024');
  await filter.fill('flat');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-7 of 7');
  await expect(page.getByTestId('row')).toHaveCount(7);
});

