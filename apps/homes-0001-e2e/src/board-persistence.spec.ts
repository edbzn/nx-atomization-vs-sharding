import { expect, test } from '@playwright/test';

test('plans work on the board and keeps it after a reload (10 steps)', async ({ page }) => {
  await page.goto('/board');
  const newCard = page.getByRole('textbox', { name: 'New card' });
  const filter = page.getByRole('searchbox', { name: 'Filter cards' });
  const cardsIn = (column: string) => page.getByRole('region', { name: column }).getByTestId('card');
  await newCard.pressSequentially('Ship terrace spruce');
  await newCard.press('Enter');
  await newCard.fill('Restock townhouse pine');
  await newCard.press('Enter');
  await expect(cardsIn('To do')).toHaveCount(2);
  await expect(cardsIn('In progress')).toHaveCount(0);
  await expect(cardsIn('Done')).toHaveCount(0);
  await expect(page.getByTestId('board-summary')).toHaveText('0 of 2 done');
  await page.getByRole('button', { name: 'Start Ship terrace spruce' }).click();
  await page.getByRole('button', { name: 'Start Restock townhouse pine' }).click();
  await expect(cardsIn('To do')).toHaveCount(0);
  await expect(cardsIn('In progress')).toHaveCount(2);
  await expect(cardsIn('Done')).toHaveCount(0);
  await expect(page.getByTestId('board-summary')).toHaveText('0 of 2 done');
  await newCard.fill('Email townhouse juniper');
  await newCard.press('Enter');
  await page.getByRole('button', { name: 'Finish Restock townhouse pine' }).click();
  await expect(cardsIn('To do')).toHaveCount(1);
  await expect(cardsIn('In progress')).toHaveCount(1);
  await expect(cardsIn('Done')).toHaveCount(1);
  await expect(page.getByTestId('board-summary')).toHaveText('1 of 3 done');
  await page.getByRole('button', { name: 'Finish Ship terrace spruce' }).click();
  await newCard.pressSequentially('Restock suite atlas');
  await newCard.press('Enter');
  await expect(cardsIn('To do')).toHaveCount(2);
  await expect(cardsIn('In progress')).toHaveCount(0);
  await expect(cardsIn('Done')).toHaveCount(2);
  await expect(page.getByTestId('board-summary')).toHaveText('2 of 4 done');
  await page.getByRole('button', { name: 'Start Restock suite atlas' }).click();
  await filter.fill('pine');
  await expect(cardsIn('To do')).toHaveCount(0);
  await expect(cardsIn('In progress')).toHaveCount(0);
  await expect(cardsIn('Done')).toHaveCount(1);
  await expect(page.getByTestId('board-summary')).toHaveText('2 of 4 done');
  await page.reload();
  await expect(cardsIn('To do')).toHaveCount(1);
  await expect(cardsIn('In progress')).toHaveCount(1);
  await expect(cardsIn('Done')).toHaveCount(2);
  await expect(page.getByTestId('board-summary')).toHaveText('2 of 4 done');
});

