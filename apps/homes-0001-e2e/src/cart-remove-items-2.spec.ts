import { expect, test } from '@playwright/test';

test('adds 2 listings to the cart and updates totals', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Homes Finder');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: 'Listings' }).click();
  await page.getByRole('searchbox', { name: 'Filter' }).fill('LST-0067');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await page.getByTestId('row').first().click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Renovated Bungalow');
  await expect(page.getByTestId('quantity')).toHaveText('1');
  await page.getByRole('button', { name: 'Add to cart' }).click();
  await expect(page.getByRole('status').last()).toHaveText('Added 1 × Renovated Bungalow');
  await expect(page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ })).toHaveText('Cart (1)');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: 'Listings' }).click();
  await page.getByRole('searchbox', { name: 'Filter' }).fill('LST-0019');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await page.getByTestId('row').first().click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Sunny Duplex');
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await expect(page.getByTestId('quantity')).toHaveText('3');
  await page.getByRole('button', { name: 'Add to cart' }).click();
  await expect(page.getByRole('status').last()).toHaveText('Added 3 × Sunny Duplex');
  await expect(page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ })).toHaveText('Cart (4)');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ }).click();
  await expect(page.getByTestId('cart-line')).toHaveCount(2);
  await expect(page.getByTestId('line-quantity').nth(0)).toHaveText('1');
  await expect(page.getByTestId('line-total').nth(0)).toHaveText('$1,997.37');
  await expect(page.getByTestId('line-quantity').nth(1)).toHaveText('3');
  await expect(page.getByTestId('line-total').nth(1)).toHaveText('$27,724.02');
  await expect(page.getByTestId('cart-subtotal')).toHaveText('Subtotal: $29,721.39');
  await page.getByRole('button', { name: 'Remove LST-0019' }).click();
  await expect(page.getByTestId('cart-line')).toHaveCount(1);
  await expect(page.getByTestId('line-quantity').nth(0)).toHaveText('1');
  await expect(page.getByTestId('line-total').nth(0)).toHaveText('$1,997.37');
  await expect(page.getByTestId('cart-subtotal')).toHaveText('Subtotal: $1,997.37');
});

