import { expect, test } from '@playwright/test';

test('adds 4 listings to the cart and updates totals', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Homes Finder');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: 'Listings' }).click();
  await page.getByRole('searchbox', { name: 'Filter' }).fill('LST-0073');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await page.getByTestId('row').first().click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Spacious Annex');
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await expect(page.getByTestId('quantity')).toHaveText('2');
  await page.getByRole('button', { name: 'Add to cart' }).click();
  await expect(page.getByRole('status').last()).toHaveText('Added 2 × Spacious Annex');
  await expect(page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ })).toHaveText('Cart (2)');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: 'Listings' }).click();
  await page.getByRole('searchbox', { name: 'Filter' }).fill('LST-0059');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await page.getByTestId('row').first().click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Corner Bungalow');
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await expect(page.getByTestId('quantity')).toHaveText('6');
  await page.getByRole('button', { name: 'Add to cart' }).click();
  await expect(page.getByRole('status').last()).toHaveText('Added 6 × Corner Bungalow');
  await expect(page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ })).toHaveText('Cart (8)');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: 'Listings' }).click();
  await page.getByRole('searchbox', { name: 'Filter' }).fill('LST-0096');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await page.getByTestId('row').first().click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Modern Villa');
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await expect(page.getByTestId('quantity')).toHaveText('6');
  await page.getByRole('button', { name: 'Add to cart' }).click();
  await expect(page.getByRole('status').last()).toHaveText('Added 6 × Modern Villa');
  await expect(page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ })).toHaveText('Cart (14)');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: 'Listings' }).click();
  await page.getByRole('searchbox', { name: 'Filter' }).fill('LST-0038');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await page.getByTestId('row').first().click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Corner Townhouse');
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await expect(page.getByTestId('quantity')).toHaveText('4');
  await page.getByRole('button', { name: 'Add to cart' }).click();
  await expect(page.getByRole('status').last()).toHaveText('Added 4 × Corner Townhouse');
  await expect(page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ })).toHaveText('Cart (18)');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ }).click();
  await expect(page.getByTestId('cart-line')).toHaveCount(4);
  await expect(page.getByTestId('line-quantity').nth(0)).toHaveText('2');
  await expect(page.getByTestId('line-total').nth(0)).toHaveText('$10,624.04');
  await expect(page.getByTestId('line-quantity').nth(1)).toHaveText('6');
  await expect(page.getByTestId('line-total').nth(1)).toHaveText('$32,143.20');
  await expect(page.getByTestId('line-quantity').nth(2)).toHaveText('6');
  await expect(page.getByTestId('line-total').nth(2)).toHaveText('$14,558.28');
  await expect(page.getByTestId('line-quantity').nth(3)).toHaveText('4');
  await expect(page.getByTestId('line-total').nth(3)).toHaveText('$2,117.64');
  await expect(page.getByTestId('cart-subtotal')).toHaveText('Subtotal: $59,443.16');
});
