  await page.getByTestId('row').filter({ hasText: 'LST-0027' }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Furnished Bungalow');
  await expect(page.getByTestId('detail-price')).toHaveText('$4,681.36');
