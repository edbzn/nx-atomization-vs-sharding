import { expect, test } from '@playwright/test';

test('filters, sorts and pages the listings catalog (6 steps)', async ({ page }) => {
  await page.goto('/catalog');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Listings');
  const filter = page.getByRole('searchbox', { name: 'Filter' });
  await page.getByRole('button', { name: 'Next' }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 11-20 of 96');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('LST-0011');
  await filter.clear();
  await filter.pressSequentially('office');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 20');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await page.getByRole('button', { name: /^Reference/ }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 20');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('LST-0005');
  await filter.fill('Hist');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-6 of 6');
  await expect(page.getByTestId('row')).toHaveCount(6);
  await filter.clear();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 96');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('LST-0001');
  await filter.clear();
  await filter.pressSequentially('Corn');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 12');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await page.getByTestId('row').filter({ hasText: 'LST-0010' }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Corner Bungalow');
  await expect(page.getByTestId('detail-price')).toHaveText('$6,182.57');
});

