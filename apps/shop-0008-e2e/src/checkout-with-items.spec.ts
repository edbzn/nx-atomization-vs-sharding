import { expect, test } from '@playwright/test';

test('validates the checkout form and places an order (7 edits)', async ({ page }) => {
  await page.goto('/checkout');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Checkout');
  await page.getByRole('button', { name: 'Place order' }).click();
  await expect(page.getByTestId('error-summary')).toHaveText('7 errors');
  await expect(page.getByRole('alert')).toHaveCount(7);
  await page.getByRole('textbox', { name: 'Address', exact: true }).fill('Orbitstraat 212');
  await expect(page.getByRole('textbox', { name: 'Address', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Full name', exact: true }).clear();
  await page.getByRole('textbox', { name: 'Full name', exact: true }).pressSequentially('Bea Claessens');
  await expect(page.getByRole('textbox', { name: 'Full name', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Email', exact: true }).fill('zoe.de.smet86@example.com');
  await expect(page.getByRole('textbox', { name: 'Email', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Postal code', exact: true }).fill('abcd');
  await expect(page.getByRole('textbox', { name: 'Postal code', exact: true })).toHaveAccessibleDescription('Postal code must be 4 digits');
  await page.getByRole('textbox', { name: 'City', exact: true }).fill('Hasselt');
  await expect(page.getByRole('textbox', { name: 'City', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Address', exact: true }).fill('Valestraat 247');
  await expect(page.getByRole('textbox', { name: 'Address', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('button', { name: 'Place order' }).click();
  await expect(page.getByTestId('error-summary')).toHaveText('3 errors');
  await expect(page.getByRole('alert')).toHaveCount(3);
  await page.getByRole('textbox', { name: 'Postal code', exact: true }).fill('8006');
  await expect(page.getByRole('textbox', { name: 'Postal code', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('combobox', { name: 'Delivery' }).selectOption('Express');
  await page.getByRole('checkbox', { name: 'I accept the terms' }).check();
  await page.getByRole('button', { name: 'Place order' }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Thank you, Bea Claessens');
  await expect(page.getByTestId('order-reference')).toHaveText('REF-13FOFON');
  await expect(page.getByTestId('order-total')).toHaveText('0 items · $12.95');
});

