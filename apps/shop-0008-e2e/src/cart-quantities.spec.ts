import { expect, test } from '@playwright/test';

test('adds 2 orders to the cart and updates totals', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Shop Admin');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: 'Orders' }).click();
  await page.getByRole('searchbox', { name: 'Filter' }).fill('ORD-0047');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await page.getByTestId('row').first().click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Preorder Case');
  await expect(page.getByTestId('quantity')).toHaveText('1');
  await page.getByRole('button', { name: 'Add to cart' }).click();
  await expect(page.getByRole('status').last()).toHaveText('Added 1 × Preorder Case');
  await expect(page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ })).toHaveText('Cart (1)');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: 'Orders' }).click();
  await page.getByRole('searchbox', { name: 'Filter' }).fill('ORD-0093');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await page.getByTestId('row').first().click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Bulk Kit');
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await expect(page.getByTestId('quantity')).toHaveText('4');
  await page.getByRole('button', { name: 'Add to cart' }).click();
  await expect(page.getByRole('status').last()).toHaveText('Added 4 × Bulk Kit');
  await expect(page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ })).toHaveText('Cart (5)');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ }).click();
  await expect(page.getByTestId('cart-line')).toHaveCount(2);
  await expect(page.getByTestId('line-quantity').nth(0)).toHaveText('1');
  await expect(page.getByTestId('line-total').nth(0)).toHaveText('$603.50');
  await expect(page.getByTestId('line-quantity').nth(1)).toHaveText('4');
  await expect(page.getByTestId('line-total').nth(1)).toHaveText('$4,944.96');
  await expect(page.getByTestId('cart-subtotal')).toHaveText('Subtotal: $5,548.46');
  await page.getByRole('button', { name: 'Remove ORD-0093' }).click();
  await expect(page.getByTestId('cart-line')).toHaveCount(1);
  await expect(page.getByTestId('line-quantity').nth(0)).toHaveText('1');
  await expect(page.getByTestId('line-total').nth(0)).toHaveText('$603.50');
  await expect(page.getByTestId('cart-subtotal')).toHaveText('Subtotal: $603.50');
});

