import { expect, test } from '@playwright/test';

test('validates the checkout form and places an order (10 edits)', async ({ page }) => {
  await page.goto('/checkout');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Checkout');
  await page.getByRole('textbox', { name: 'Full name', exact: true }).fill('Al');
  await expect(page.getByRole('textbox', { name: 'Full name', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'City', exact: true }).clear();
  await page.getByRole('textbox', { name: 'City', exact: true }).pressSequentially('Mechelen');
  await expect(page.getByRole('textbox', { name: 'City', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Postal code', exact: true }).fill('2536');
  await expect(page.getByRole('textbox', { name: 'Postal code', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'City', exact: true }).fill('Mechelen');
  await expect(page.getByRole('textbox', { name: 'City', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('button', { name: 'Place order' }).click();
  await expect(page.getByTestId('error-summary')).toHaveText('5 errors');
  await expect(page.getByRole('alert')).toHaveCount(5);
  await page.getByRole('textbox', { name: 'Postal code', exact: true }).fill('3542');
  await expect(page.getByRole('textbox', { name: 'Postal code', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Email', exact: true }).clear();
  await page.getByRole('textbox', { name: 'Email', exact: true }).pressSequentially('jane@example');
  await expect(page.getByRole('textbox', { name: 'Email', exact: true })).toHaveAccessibleDescription('Enter a valid email address');
  await page.getByRole('textbox', { name: 'Full name', exact: true }).fill('Ruben Michiels');
  await expect(page.getByRole('textbox', { name: 'Full name', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Postal code', exact: true }).fill('2021');
  await expect(page.getByRole('textbox', { name: 'Postal code', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Full name', exact: true }).fill('Jo');
  await expect(page.getByRole('textbox', { name: 'Full name', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Postal code', exact: true }).clear();
  await page.getByRole('textbox', { name: 'Postal code', exact: true }).pressSequentially('12345');
  await expect(page.getByRole('textbox', { name: 'Postal code', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Full name', exact: true }).fill('Bea Hendrickx');
  await expect(page.getByRole('textbox', { name: 'Full name', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Email', exact: true }).fill('tom.cools5@example.com');
  await expect(page.getByRole('textbox', { name: 'Email', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Address', exact: true }).clear();
  await page.getByRole('textbox', { name: 'Address', exact: true }).pressSequentially('Coralstraat 72');
  await expect(page.getByRole('textbox', { name: 'Address', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Postal code', exact: true }).fill('7555');
  await expect(page.getByRole('textbox', { name: 'Postal code', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('combobox', { name: 'Delivery' }).selectOption('Standard');
  await page.getByRole('checkbox', { name: 'I accept the terms' }).check();
  await page.getByRole('button', { name: 'Place order' }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Thank you, Bea Hendrickx');
  await expect(page.getByTestId('order-reference')).toHaveText('REF-1T41W4N');
  await expect(page.getByTestId('order-total')).toHaveText('0 items · $4.95');
});

