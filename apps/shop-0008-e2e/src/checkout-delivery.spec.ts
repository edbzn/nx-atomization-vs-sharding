import { expect, test } from '@playwright/test';

test('validates the checkout form and places an order with items (6 edits)', async ({ page }) => {
  await page.goto('/catalog');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: 'Orders' }).click();
  await page.getByRole('searchbox', { name: 'Filter' }).fill('ORD-0077');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await page.getByTestId('row').first().click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Store Box');
  await expect(page.getByTestId('quantity')).toHaveText('1');
  await page.getByRole('button', { name: 'Add to cart' }).click();
  await expect(page.getByRole('status').last()).toHaveText('Added 1 × Store Box');
  await expect(page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ })).toHaveText('Cart (1)');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: 'Orders' }).click();
  await page.getByRole('searchbox', { name: 'Filter' }).fill('ORD-0069');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await page.getByTestId('row').first().click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Bulk Pack');
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await expect(page.getByTestId('quantity')).toHaveText('4');
  await page.getByRole('button', { name: 'Add to cart' }).click();
  await expect(page.getByRole('status').last()).toHaveText('Added 4 × Bulk Pack');
  await expect(page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ })).toHaveText('Cart (5)');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ }).click();
  await page.getByRole('link', { name: 'Proceed to checkout' }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Checkout');
  await page.getByRole('textbox', { name: 'Postal code', exact: true }).fill('5988');
  await expect(page.getByRole('textbox', { name: 'Postal code', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Address', exact: true }).fill('Garnetstraat 85');
  await expect(page.getByRole('textbox', { name: 'Address', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Full name', exact: true }).fill('Ruben Coppens');
  await expect(page.getByRole('textbox', { name: 'Full name', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'City', exact: true }).fill('Mechelen');
  await expect(page.getByRole('textbox', { name: 'City', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Full name', exact: true }).clear();
  await page.getByRole('textbox', { name: 'Full name', exact: true }).pressSequentially('Jo');
  await expect(page.getByRole('textbox', { name: 'Full name', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Email', exact: true }).fill('cas.desmet85@example.com');
  await expect(page.getByRole('textbox', { name: 'Email', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Full name', exact: true }).clear();
  await page.getByRole('textbox', { name: 'Full name', exact: true }).pressSequentially('Victor Claessens');
  await expect(page.getByRole('textbox', { name: 'Full name', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('combobox', { name: 'Delivery' }).selectOption('Standard');
  await page.getByRole('checkbox', { name: 'I accept the terms' }).check();
  await page.getByRole('button', { name: 'Place order' }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Thank you, Victor Claessens');
  await expect(page.getByTestId('order-reference')).toHaveText('REF-070BLTS');
  await expect(page.getByTestId('order-total')).toHaveText('5 items · $6,689.27');
});

