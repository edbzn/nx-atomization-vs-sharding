import { expect, test } from '@playwright/test';

test('plans work on the board and keeps it after a reload (10 steps)', async ({ page }) => {
  await page.goto('/board');
  const newCard = page.getByRole('textbox', { name: 'New card' });
  const filter = page.getByRole('searchbox', { name: 'Filter cards' });
  const cardsIn = (column: string) => page.getByRole('region', { name: column }).getByTestId('card');
  await newCard.fill('Email lot kestrel');
  await newCard.press('Enter');
  await newCard.fill('Check basket jade');
  await newCard.press('Enter');
  await expect(cardsIn('To do')).toHaveCount(2);
  await expect(cardsIn('In progress')).toHaveCount(0);
  await expect(cardsIn('Done')).toHaveCount(0);
  await expect(page.getByTestId('board-summary')).toHaveText('0 of 2 done');
  await page.getByRole('button', { name: 'Start Email lot kestrel' }).click();
  await page.getByRole('button', { name: 'Finish Email lot kestrel' }).click();
  await expect(cardsIn('To do')).toHaveCount(1);
  await expect(cardsIn('In progress')).toHaveCount(0);
  await expect(cardsIn('Done')).toHaveCount(1);
  await expect(page.getByTestId('board-summary')).toHaveText('1 of 2 done');
  await newCard.pressSequentially('Restock bundle birch');
  await newCard.press('Enter');
  await newCard.pressSequentially('Restock set kestrel');
  await newCard.press('Enter');
  await expect(cardsIn('To do')).toHaveCount(3);
  await expect(cardsIn('In progress')).toHaveCount(0);
  await expect(cardsIn('Done')).toHaveCount(1);
  await expect(page.getByTestId('board-summary')).toHaveText('1 of 4 done');
  await page.getByRole('button', { name: 'Delete Email lot kestrel' }).click();
  await filter.fill('Chec');
  await expect(cardsIn('To do')).toHaveCount(1);
  await expect(cardsIn('In progress')).toHaveCount(0);
  await expect(cardsIn('Done')).toHaveCount(0);
  await expect(page.getByTestId('board-summary')).toHaveText('0 of 3 done');
  await newCard.fill('Ship kit meadow');
  await newCard.press('Enter');
  await page.getByRole('button', { name: 'Delete Check basket jade' }).click();
  await expect(cardsIn('To do')).toHaveCount(0);
  await expect(cardsIn('In progress')).toHaveCount(0);
  await expect(cardsIn('Done')).toHaveCount(0);
  await expect(page.getByTestId('board-summary')).toHaveText('0 of 3 done');
  await page.reload();
  await expect(cardsIn('To do')).toHaveCount(3);
  await expect(cardsIn('In progress')).toHaveCount(0);
  await expect(cardsIn('Done')).toHaveCount(0);
  await expect(page.getByTestId('board-summary')).toHaveText('0 of 3 done');
});

