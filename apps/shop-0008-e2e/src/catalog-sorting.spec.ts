import { expect, test } from '@playwright/test';

test('filters, sorts and pages the orders catalog (5 steps)', async ({ page }) => {
  await page.goto('/catalog');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Orders');
  const filter = page.getByRole('searchbox', { name: 'Filter' });
  await page.getByRole('button', { name: /^Reference/ }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 140');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('ORD-0001');
  await filter.fill('crate');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 14');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await page.getByRole('button', { name: /^Price/ }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 14');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('ORD-0067');
  await filter.fill('paid');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 27');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await page.getByRole('button', { name: 'Next' }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 11-20 of 27');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('ORD-0034');
  await page.getByTestId('row').filter({ hasText: 'ORD-0027' }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Preorder Basket');
  await expect(page.getByTestId('detail-price')).toHaveText('$6,956.88');
});

