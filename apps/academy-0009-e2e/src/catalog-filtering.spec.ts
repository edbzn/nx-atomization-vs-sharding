import { expect, test } from '@playwright/test';

test('filters, sorts and pages the courses catalog (6 steps)', async ({ page }) => {
  await page.goto('/catalog');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Courses');
  const filter = page.getByRole('searchbox', { name: 'Filter' });
  await filter.fill('advanced');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-7 of 7');
  await expect(page.getByTestId('row')).toHaveCount(7);
  await filter.clear();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 64');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('CRS-0001');
  await filter.clear();
  await filter.pressSequentially('CRS-0022');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-1 of 1');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await page.getByRole('button', { name: /^Reference/ }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-1 of 1');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await expect(page.getByTestId('row').first()).toContainText('CRS-0022');
  await page.getByRole('button', { name: /^Price/ }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-1 of 1');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await expect(page.getByTestId('row').first()).toContainText('CRS-0022');
  await filter.clear();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 64');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('CRS-0023');
  await page.getByTestId('row').filter({ hasText: 'CRS-0063' }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Applied Spanish');
  await expect(page.getByTestId('detail-price')).toHaveText('$335.29');
});

