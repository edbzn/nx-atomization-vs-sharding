import { expect, test } from '@playwright/test';

test('filters, sorts and pages the listings catalog (3 steps)', async ({ page }) => {
  await page.goto('/catalog');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Listings');
  const filter = page.getByRole('searchbox', { name: 'Filter' });
  await page.getByRole('button', { name: /^Price/ }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 96');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('LST-0004');
  await page.getByRole('button', { name: /^Price/ }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 96');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('LST-0080');
  await filter.fill('LST-0011');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-1 of 1');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await page.getByTestId('row').filter({ hasText: 'LST-0011' }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Corner Annex');
  await expect(page.getByTestId('detail-price')).toHaveText('$8,496.60');
});

