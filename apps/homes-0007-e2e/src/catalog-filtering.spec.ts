import { expect, test } from '@playwright/test';

test('filters, sorts and pages the listings catalog (9 steps)', async ({ page }) => {
  await page.goto('/catalog');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Listings');
  const filter = page.getByRole('searchbox', { name: 'Filter' });
  await filter.fill('lst-001');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 10');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await filter.clear();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 96');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('LST-0001');
  await page.getByRole('button', { name: 'Next' }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 11-20 of 96');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('LST-0011');
  await page.getByRole('button', { name: /^Reference/ }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 96');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('LST-0001');
  await filter.clear();
  await filter.pressSequentially('villa');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 12');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await page.getByRole('button', { name: 'Next' }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 11-12 of 12');
  await expect(page.getByTestId('row')).toHaveCount(2);
  await expect(page.getByTestId('row').first()).toContainText('LST-0085');
  await filter.fill('lst-000');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-9 of 9');
  await expect(page.getByTestId('row')).toHaveCount(9);
  await filter.clear();
  await filter.pressSequentially('lst-000');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-9 of 9');
  await expect(page.getByTestId('row')).toHaveCount(9);
  await filter.clear();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 96');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('LST-0001');
});

