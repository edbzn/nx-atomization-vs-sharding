import { expect, test } from '@playwright/test';

test('filters, sorts and pages the courses catalog (7 steps)', async ({ page }) => {
  await page.goto('/catalog');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Courses');
  const filter = page.getByRole('searchbox', { name: 'Filter' });
  await page.getByRole('button', { name: 'Next' }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 11-20 of 64');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('CRS-0011');
  await page.getByRole('button', { name: 'Next' }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 21-30 of 64');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('CRS-0021');
  await page.getByRole('button', { name: /^Price/ }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 64');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('CRS-0058');
  await page.getByRole('button', { name: /^Price/ }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 64');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('CRS-0063');
  await page.getByRole('button', { name: 'Next' }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 11-20 of 64');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('CRS-0006');
  await filter.clear();
  await filter.pressSequentially('crs-000');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-9 of 9');
  await expect(page.getByTestId('row')).toHaveCount(9);
  await filter.clear();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 64');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('CRS-0063');
  await page.getByTestId('row').filter({ hasText: 'CRS-0054' }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Modern Chemistry');
  await expect(page.getByTestId('detail-price')).toHaveText('$8,515.53');
});

