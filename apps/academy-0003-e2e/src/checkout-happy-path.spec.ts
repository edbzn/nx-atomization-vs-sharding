import { expect, test } from '@playwright/test';

test('validates the checkout form and places an order (7 edits)', async ({ page }) => {
  await page.goto('/checkout');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Checkout');
  await page.getByRole('button', { name: 'Place order' }).click();
  await expect(page.getByTestId('error-summary')).toHaveText('7 errors');
  await expect(page.getByRole('alert')).toHaveCount(7);
  await page.getByRole('textbox', { name: 'Postal code', exact: true }).fill('9043');
  await expect(page.getByRole('textbox', { name: 'Postal code', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Email', exact: true }).fill('jane@example');
  await expect(page.getByRole('textbox', { name: 'Email', exact: true })).toHaveAccessibleDescription('Enter a valid email address');
  await page.getByRole('textbox', { name: 'Email', exact: true }).fill('jane@example');
  await expect(page.getByRole('textbox', { name: 'Email', exact: true })).toHaveAccessibleDescription('Enter a valid email address');
  await page.getByRole('textbox', { name: 'Full name', exact: true }).fill('Jo');
  await expect(page.getByRole('textbox', { name: 'Full name', exact: true })).toHaveAccessibleDescription('Full name must be at least 3 characters');
  await page.getByRole('textbox', { name: 'Postal code', exact: true }).fill('1832');
  await expect(page.getByRole('textbox', { name: 'Postal code', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('button', { name: 'Place order' }).click();
  await expect(page.getByTestId('error-summary')).toHaveText('6 errors');
  await expect(page.getByRole('alert')).toHaveCount(6);
  await page.getByRole('textbox', { name: 'Address', exact: true }).fill('Rd');
  await expect(page.getByRole('textbox', { name: 'Address', exact: true })).toHaveAccessibleDescription('Address must be at least 5 characters');
  await page.getByRole('textbox', { name: 'Address', exact: true }).fill('Flintstraat 228');
  await expect(page.getByRole('textbox', { name: 'Address', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('button', { name: 'Place order' }).click();
  await expect(page.getByTestId('error-summary')).toHaveText('5 errors');
  await expect(page.getByRole('alert')).toHaveCount(5);
  await page.getByRole('textbox', { name: 'Full name', exact: true }).fill('Ruben Lemmens');
  await expect(page.getByRole('textbox', { name: 'Full name', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Email', exact: true }).fill('yara.verhoeven53@example.com');
  await expect(page.getByRole('textbox', { name: 'Email', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'City', exact: true }).clear();
  await page.getByRole('textbox', { name: 'City', exact: true }).pressSequentially('Brugge');
  await expect(page.getByRole('textbox', { name: 'City', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('combobox', { name: 'Delivery' }).selectOption('Standard');
  await page.getByRole('checkbox', { name: 'I accept the terms' }).check();
  await page.getByRole('button', { name: 'Place order' }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Thank you, Ruben Lemmens');
  await expect(page.getByTestId('order-reference')).toHaveText('REF-18ZBO2U');
  await expect(page.getByTestId('order-total')).toHaveText('0 items · $4.95');
});

