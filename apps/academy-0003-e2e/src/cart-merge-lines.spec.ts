import { expect, test } from '@playwright/test';

test('adds 2 courses to the cart and updates totals', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Academy Portal');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: 'Courses' }).click();
  await page.getByRole('searchbox', { name: 'Filter' }).fill('CRS-0057');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await page.getByTestId('row').first().click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Practical Statistics');
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await expect(page.getByTestId('quantity')).toHaveText('5');
  await page.getByRole('button', { name: 'Add to cart' }).click();
  await expect(page.getByRole('status').last()).toHaveText('Added 5 × Practical Statistics');
  await expect(page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ })).toHaveText('Cart (5)');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: 'Courses' }).click();
  await page.getByRole('searchbox', { name: 'Filter' }).fill('CRS-0041');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await page.getByTestId('row').first().click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Remote Robotics');
  await expect(page.getByTestId('quantity')).toHaveText('1');
  await page.getByRole('button', { name: 'Add to cart' }).click();
  await expect(page.getByRole('status').last()).toHaveText('Added 1 × Remote Robotics');
  await expect(page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ })).toHaveText('Cart (6)');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ }).click();
  await expect(page.getByTestId('cart-line')).toHaveCount(2);
  await expect(page.getByTestId('line-quantity').nth(0)).toHaveText('5');
  await expect(page.getByTestId('line-total').nth(0)).toHaveText('$498.55');
  await expect(page.getByTestId('line-quantity').nth(1)).toHaveText('1');
  await expect(page.getByTestId('line-total').nth(1)).toHaveText('$4,915.71');
  await expect(page.getByTestId('cart-subtotal')).toHaveText('Subtotal: $5,414.26');
  await page.getByRole('button', { name: 'Remove CRS-0041' }).click();
  await expect(page.getByTestId('cart-line')).toHaveCount(1);
  await expect(page.getByTestId('line-quantity').nth(0)).toHaveText('5');
  await expect(page.getByTestId('line-total').nth(0)).toHaveText('$498.55');
  await expect(page.getByTestId('cart-subtotal')).toHaveText('Subtotal: $498.55');
});

