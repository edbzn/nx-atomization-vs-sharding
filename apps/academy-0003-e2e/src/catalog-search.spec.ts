import { expect, test } from '@playwright/test';

test('filters, sorts and pages the courses catalog (8 steps)', async ({ page }) => {
  await page.goto('/catalog');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Courses');
  const filter = page.getByRole('searchbox', { name: 'Filter' });
  await filter.fill('botan');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-3 of 3');
  await expect(page.getByTestId('row')).toHaveCount(3);
  await filter.fill('CRS-0020');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-1 of 1');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await page.getByRole('button', { name: /^Price/ }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-1 of 1');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await expect(page.getByTestId('row').first()).toContainText('CRS-0020');
  await filter.clear();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 64');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('CRS-0058');
  await filter.fill('CRS-0030');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-1 of 1');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await filter.fill('seminar');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 12');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await page.getByRole('button', { name: 'Next' }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 11-12 of 12');
  await expect(page.getByTestId('row')).toHaveCount(2);
  await expect(page.getByTestId('row').first()).toContainText('CRS-0052');
  await filter.clear();
  await filter.pressSequentially('chemi');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 11');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await page.getByTestId('row').filter({ hasText: 'CRS-0006' }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Evening Chemistry');
  await expect(page.getByTestId('detail-price')).toHaveText('$8,162.70');
});

