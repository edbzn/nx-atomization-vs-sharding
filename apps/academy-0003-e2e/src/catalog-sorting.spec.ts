import { expect, test } from '@playwright/test';

test('filters, sorts and pages the courses catalog (6 steps)', async ({ page }) => {
  await page.goto('/catalog');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Courses');
  const filter = page.getByRole('searchbox', { name: 'Filter' });
  await page.getByRole('button', { name: 'Next' }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 11-20 of 64');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('CRS-0011');
  await page.getByRole('button', { name: 'Next' }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 21-30 of 64');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('CRS-0021');
  await filter.fill('che');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 11');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await filter.clear();
  await filter.pressSequentially('advanced');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 12');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await filter.fill('online');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 10');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await filter.fill('beginner');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 12');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await page.getByTestId('row').filter({ hasText: 'CRS-0024' }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Hands-on Robotics');
  await expect(page.getByTestId('detail-price')).toHaveText('$8,150.47');
});

