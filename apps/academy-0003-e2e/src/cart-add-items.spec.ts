import { expect, test } from '@playwright/test';

test('adds 3 courses to the cart and updates totals', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Academy Portal');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: 'Courses' }).click();
  await page.getByRole('searchbox', { name: 'Filter' }).fill('CRS-0008');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await page.getByTestId('row').first().click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Hands-on Typing');
  await expect(page.getByTestId('quantity')).toHaveText('1');
  await page.getByRole('button', { name: 'Add to cart' }).click();
  await expect(page.getByRole('status').last()).toHaveText('Added 1 × Hands-on Typing');
  await expect(page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ })).toHaveText('Cart (1)');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: 'Courses' }).click();
  await page.getByRole('searchbox', { name: 'Filter' }).fill('CRS-0059');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await page.getByTestId('row').first().click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Applied Typing');
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await expect(page.getByTestId('quantity')).toHaveText('2');
  await page.getByRole('button', { name: 'Add to cart' }).click();
  await expect(page.getByRole('status').last()).toHaveText('Added 2 × Applied Typing');
  await expect(page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ })).toHaveText('Cart (3)');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: 'Courses' }).click();
  await page.getByRole('searchbox', { name: 'Filter' }).fill('CRS-0046');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await page.getByTestId('row').first().click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Weekend Botany');
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await expect(page.getByTestId('quantity')).toHaveText('4');
  await page.getByRole('button', { name: 'Add to cart' }).click();
  await expect(page.getByRole('status').last()).toHaveText('Added 4 × Weekend Botany');
  await expect(page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ })).toHaveText('Cart (7)');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ }).click();
  await expect(page.getByTestId('cart-line')).toHaveCount(3);
  await expect(page.getByTestId('line-quantity').nth(0)).toHaveText('1');
  await expect(page.getByTestId('line-total').nth(0)).toHaveText('$2,908.78');
  await expect(page.getByTestId('line-quantity').nth(1)).toHaveText('2');
  await expect(page.getByTestId('line-total').nth(1)).toHaveText('$16,677.84');
  await expect(page.getByTestId('line-quantity').nth(2)).toHaveText('4');
  await expect(page.getByTestId('line-total').nth(2)).toHaveText('$24,074.92');
  await expect(page.getByTestId('cart-subtotal')).toHaveText('Subtotal: $43,661.54');
});

