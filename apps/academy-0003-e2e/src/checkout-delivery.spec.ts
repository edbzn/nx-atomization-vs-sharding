import { expect, test } from '@playwright/test';

test('validates the checkout form and places an order (5 edits)', async ({ page }) => {
  await page.goto('/checkout');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Checkout');
  await page.getByRole('button', { name: 'Place order' }).click();
  await expect(page.getByTestId('error-summary')).toHaveText('7 errors');
  await expect(page.getByRole('alert')).toHaveCount(7);
  await page.getByRole('textbox', { name: 'City', exact: true }).fill('Hasselt');
  await expect(page.getByRole('textbox', { name: 'City', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'City', exact: true }).fill('Gent');
  await expect(page.getByRole('textbox', { name: 'City', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Address', exact: true }).fill('Rd');
  await expect(page.getByRole('textbox', { name: 'Address', exact: true })).toHaveAccessibleDescription('Address must be at least 5 characters');
  await page.getByRole('button', { name: 'Place order' }).click();
  await expect(page.getByTestId('error-summary')).toHaveText('6 errors');
  await expect(page.getByRole('alert')).toHaveCount(6);
  await page.getByRole('textbox', { name: 'Full name', exact: true }).clear();
  await page.getByRole('textbox', { name: 'Full name', exact: true }).pressSequentially('Noor Bogaert');
  await expect(page.getByRole('textbox', { name: 'Full name', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Full name', exact: true }).clear();
  await page.getByRole('textbox', { name: 'Full name', exact: true }).pressSequentially('Pia Hendrickx');
  await expect(page.getByRole('textbox', { name: 'Full name', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('button', { name: 'Place order' }).click();
  await expect(page.getByTestId('error-summary')).toHaveText('5 errors');
  await expect(page.getByRole('alert')).toHaveCount(5);
  await page.getByRole('textbox', { name: 'Email', exact: true }).fill('zoe.michiels2@example.com');
  await expect(page.getByRole('textbox', { name: 'Email', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Address', exact: true }).fill('Sprucestraat 24');
  await expect(page.getByRole('textbox', { name: 'Address', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Postal code', exact: true }).fill('7643');
  await expect(page.getByRole('textbox', { name: 'Postal code', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('combobox', { name: 'Delivery' }).selectOption('Pickup');
  await page.getByRole('checkbox', { name: 'I accept the terms' }).check();
  await page.getByRole('button', { name: 'Place order' }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Thank you, Pia Hendrickx');
  await expect(page.getByTestId('order-reference')).toHaveText('REF-0TA27Y8');
  await expect(page.getByTestId('order-total')).toHaveText('0 items · $0.00');
});

