import { expect, test } from '@playwright/test';

test('validates the checkout form and places an order (6 edits)', async ({ page }) => {
  await page.goto('/checkout');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Checkout');
  await page.getByRole('button', { name: 'Place order' }).click();
  await expect(page.getByTestId('error-summary')).toHaveText('7 errors');
  await expect(page.getByRole('alert')).toHaveCount(7);
  await page.getByRole('textbox', { name: 'City', exact: true }).fill('Hasselt');
  await expect(page.getByRole('textbox', { name: 'City', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Address', exact: true }).clear();
  await page.getByRole('textbox', { name: 'Address', exact: true }).pressSequentially('Ridgestraat 193');
  await expect(page.getByRole('textbox', { name: 'Address', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Email', exact: true }).fill('jane@example');
  await expect(page.getByRole('textbox', { name: 'Email', exact: true })).toHaveAccessibleDescription('Enter a valid email address');
  await page.getByRole('textbox', { name: 'Postal code', exact: true }).fill('1340');
  await expect(page.getByRole('textbox', { name: 'Postal code', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'City', exact: true }).clear();
  await page.getByRole('textbox', { name: 'City', exact: true }).pressSequentially('Namur');
  await expect(page.getByRole('textbox', { name: 'City', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'City', exact: true }).fill('Liège');
  await expect(page.getByRole('textbox', { name: 'City', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Full name', exact: true }).fill('Bea Van Damme');
  await expect(page.getByRole('textbox', { name: 'Full name', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Email', exact: true }).clear();
  await page.getByRole('textbox', { name: 'Email', exact: true }).pressSequentially('wout.coppens98@example.com');
  await expect(page.getByRole('textbox', { name: 'Email', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('combobox', { name: 'Delivery' }).selectOption('Standard');
  await page.getByRole('checkbox', { name: 'I accept the terms' }).check();
  await page.getByRole('button', { name: 'Place order' }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Thank you, Bea Van Damme');
  await expect(page.getByTestId('order-reference')).toHaveText('REF-0QLNYNP');
  await expect(page.getByTestId('order-total')).toHaveText('0 items · $4.95');
});

