import { expect, test } from '@playwright/test';

test('filters, sorts and pages the courses catalog (3 steps)', async ({ page }) => {
  await page.goto('/catalog');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Courses');
  const filter = page.getByRole('searchbox', { name: 'Filter' });
  await page.getByRole('button', { name: /^Name/ }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 64');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('CRS-0027');
  await page.getByRole('button', { name: /^Price/ }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 64');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('CRS-0058');
  await filter.fill('workshop');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 18');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await page.getByTestId('row').filter({ hasText: 'CRS-0014' }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Applied Chemistry');
  await expect(page.getByTestId('detail-price')).toHaveText('$822.64');
});

