import { expect, test } from '@playwright/test';

test('plans work on the board and keeps it after a reload (10 steps)', async ({ page }) => {
  await page.goto('/board');
  const newCard = page.getByRole('textbox', { name: 'New card' });
  const filter = page.getByRole('searchbox', { name: 'Filter cards' });
  const cardsIn = (column: string) => page.getByRole('region', { name: column }).getByTestId('card');
  await newCard.fill('Restock crate lagoon');
  await newCard.press('Enter');
  await newCard.fill('Ship case mesa');
  await newCard.press('Enter');
  await expect(cardsIn('To do')).toHaveCount(2);
  await expect(cardsIn('In progress')).toHaveCount(0);
  await expect(cardsIn('Done')).toHaveCount(0);
  await expect(page.getByTestId('board-summary')).toHaveText('0 of 2 done');
  await newCard.pressSequentially('Call lot lagoon');
  await newCard.press('Enter');
  await page.getByRole('button', { name: 'Delete Call lot lagoon' }).click();
  await expect(cardsIn('To do')).toHaveCount(2);
  await expect(cardsIn('In progress')).toHaveCount(0);
  await expect(cardsIn('Done')).toHaveCount(0);
  await expect(page.getByTestId('board-summary')).toHaveText('0 of 2 done');
  await page.getByRole('button', { name: 'Start Ship case mesa' }).click();
  await page.getByRole('button', { name: 'Start Restock crate lagoon' }).click();
  await expect(cardsIn('To do')).toHaveCount(0);
  await expect(cardsIn('In progress')).toHaveCount(2);
  await expect(cardsIn('Done')).toHaveCount(0);
  await expect(page.getByTestId('board-summary')).toHaveText('0 of 2 done');
  await newCard.fill('Email set cedar');
  await newCard.press('Enter');
  await newCard.pressSequentially('Call hamper solstice');
  await newCard.press('Enter');
  await expect(cardsIn('To do')).toHaveCount(2);
  await expect(cardsIn('In progress')).toHaveCount(2);
  await expect(cardsIn('Done')).toHaveCount(0);
  await expect(page.getByTestId('board-summary')).toHaveText('0 of 4 done');
  await page.getByRole('button', { name: 'Start Call hamper solstice' }).click();
  await page.getByRole('button', { name: 'Finish Ship case mesa' }).click();
  await expect(cardsIn('To do')).toHaveCount(1);
  await expect(cardsIn('In progress')).toHaveCount(2);
  await expect(cardsIn('Done')).toHaveCount(1);
  await expect(page.getByTestId('board-summary')).toHaveText('1 of 4 done');
  await page.reload();
  await expect(cardsIn('To do')).toHaveCount(1);
  await expect(cardsIn('In progress')).toHaveCount(2);
  await expect(cardsIn('Done')).toHaveCount(1);
  await expect(page.getByTestId('board-summary')).toHaveText('1 of 4 done');
});

