import { expect, test } from '@playwright/test';

test('filters, sorts and pages the orders catalog (4 steps)', async ({ page }) => {
  await page.goto('/catalog');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Orders');
  const filter = page.getByRole('searchbox', { name: 'Filter' });
  await filter.fill('cas');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 13');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await filter.fill('Sam');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 13');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await page.getByRole('button', { name: 'Next' }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 11-13 of 13');
  await expect(page.getByTestId('row')).toHaveCount(3);
  await expect(page.getByTestId('row').first()).toContainText('ORD-0109');
  await page.getByRole('button', { name: /^Name/ }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 13');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('ORD-0070');
  await page.getByTestId('row').filter({ hasText: 'ORD-0109' }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Sample Box');
  await expect(page.getByTestId('detail-price')).toHaveText('$795.89');
});

