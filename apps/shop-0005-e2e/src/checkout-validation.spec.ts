import { expect, test } from '@playwright/test';

test('validates the checkout form and places an order (10 edits)', async ({ page }) => {
  await page.goto('/checkout');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Checkout');
  await page.getByRole('button', { name: 'Place order' }).click();
  await expect(page.getByTestId('error-summary')).toHaveText('7 errors');
  await expect(page.getByRole('alert')).toHaveCount(7);
  await page.getByRole('textbox', { name: 'Address', exact: true }).fill('Apexstraat 99');
  await expect(page.getByRole('textbox', { name: 'Address', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Full name', exact: true }).fill('Al');
  await expect(page.getByRole('textbox', { name: 'Full name', exact: true })).toHaveAccessibleDescription('Full name must be at least 3 characters');
  await page.getByRole('textbox', { name: 'Full name', exact: true }).clear();
  await page.getByRole('textbox', { name: 'Full name', exact: true }).pressSequentially('Al');
  await expect(page.getByRole('textbox', { name: 'Full name', exact: true })).toHaveAccessibleDescription('Full name must be at least 3 characters');
  await page.getByRole('textbox', { name: 'City', exact: true }).fill('Gent');
  await expect(page.getByRole('textbox', { name: 'City', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Email', exact: true }).fill('ruben.coppens85@example.com');
  await expect(page.getByRole('textbox', { name: 'Email', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Postal code', exact: true }).clear();
  await page.getByRole('textbox', { name: 'Postal code', exact: true }).pressSequentially('2107');
  await expect(page.getByRole('textbox', { name: 'Postal code', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Postal code', exact: true }).clear();
  await page.getByRole('textbox', { name: 'Postal code', exact: true }).pressSequentially('2739');
  await expect(page.getByRole('textbox', { name: 'Postal code', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Email', exact: true }).fill('tom.claessens63@example.com');
  await expect(page.getByRole('textbox', { name: 'Email', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Full name', exact: true }).fill('Jo');
  await expect(page.getByRole('textbox', { name: 'Full name', exact: true })).toHaveAccessibleDescription('Full name must be at least 3 characters');
  await page.getByRole('button', { name: 'Place order' }).click();
  await expect(page.getByTestId('error-summary')).toHaveText('3 errors');
  await expect(page.getByRole('alert')).toHaveCount(3);
  await page.getByRole('textbox', { name: 'Email', exact: true }).clear();
  await page.getByRole('textbox', { name: 'Email', exact: true }).pressSequentially('marco.cools13@example.com');
  await expect(page.getByRole('textbox', { name: 'Email', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Full name', exact: true }).fill('Sara Cools');
  await expect(page.getByRole('textbox', { name: 'Full name', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('combobox', { name: 'Delivery' }).selectOption('Standard');
  await page.getByRole('checkbox', { name: 'I accept the terms' }).check();
  await page.getByRole('button', { name: 'Place order' }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Thank you, Sara Cools');
  await expect(page.getByTestId('order-reference')).toHaveText('REF-19KSXQU');
  await expect(page.getByTestId('order-total')).toHaveText('0 items · $4.95');
});

