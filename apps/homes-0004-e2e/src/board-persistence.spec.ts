import { expect, test } from '@playwright/test';

test('plans work on the board and keeps it after a reload (7 steps)', async ({ page }) => {
  await page.goto('/board');
  const newCard = page.getByRole('textbox', { name: 'New card' });
  const filter = page.getByRole('searchbox', { name: 'Filter cards' });
  const cardsIn = (column: string) => page.getByRole('region', { name: column }).getByTestId('card');
  await newCard.fill('Restock cottage velvet');
  await newCard.press('Enter');
  await newCard.fill('Count cottage harbor');
  await newCard.press('Enter');
  await expect(cardsIn('To do')).toHaveCount(2);
  await expect(cardsIn('In progress')).toHaveCount(0);
  await expect(cardsIn('Done')).toHaveCount(0);
  await expect(page.getByTestId('board-summary')).toHaveText('0 of 2 done');
  await newCard.pressSequentially('Restock flat cobalt');
  await newCard.press('Enter');
  await newCard.pressSequentially('Check annex sage');
  await newCard.press('Enter');
  await expect(cardsIn('To do')).toHaveCount(4);
  await expect(cardsIn('In progress')).toHaveCount(0);
  await expect(cardsIn('Done')).toHaveCount(0);
  await expect(page.getByTestId('board-summary')).toHaveText('0 of 4 done');
  await newCard.fill('Restock duplex cedar');
  await newCard.press('Enter');
  await newCard.pressSequentially('Email suite zephyr');
  await newCard.press('Enter');
  await expect(cardsIn('To do')).toHaveCount(6);
  await expect(cardsIn('In progress')).toHaveCount(0);
  await expect(cardsIn('Done')).toHaveCount(0);
  await expect(page.getByTestId('board-summary')).toHaveText('0 of 6 done');
  await page.getByRole('button', { name: 'Start Email suite zephyr' }).click();
  await expect(cardsIn('To do')).toHaveCount(5);
  await expect(cardsIn('In progress')).toHaveCount(1);
  await expect(cardsIn('Done')).toHaveCount(0);
  await expect(page.getByTestId('board-summary')).toHaveText('0 of 6 done');
  await page.reload();
  await expect(cardsIn('To do')).toHaveCount(5);
  await expect(cardsIn('In progress')).toHaveCount(1);
  await expect(cardsIn('Done')).toHaveCount(0);
  await expect(page.getByTestId('board-summary')).toHaveText('0 of 6 done');
});

test('plans work on the board and keeps it after a reload (8 steps)', async ({ page }) => {
  await page.goto('/board');
  const newCard = page.getByRole('textbox', { name: 'New card' });
  const filter = page.getByRole('searchbox', { name: 'Filter cards' });
  const cardsIn = (column: string) => page.getByRole('region', { name: column }).getByTestId('card');
  await newCard.fill('Restock bungalow lumen');
  await newCard.press('Enter');
  await newCard.fill('Count bungalow hazel');
  await newCard.press('Enter');
  await expect(cardsIn('To do')).toHaveCount(2);
  await expect(cardsIn('In progress')).toHaveCount(0);
  await expect(cardsIn('Done')).toHaveCount(0);
  await expect(page.getByTestId('board-summary')).toHaveText('0 of 2 done');
  await page.getByRole('button', { name: 'Start Count bungalow hazel' }).click();
  await page.getByRole('button', { name: 'Start Restock bungalow lumen' }).click();
  await expect(cardsIn('To do')).toHaveCount(0);
  await expect(cardsIn('In progress')).toHaveCount(2);
  await expect(cardsIn('Done')).toHaveCount(0);
  await expect(page.getByTestId('board-summary')).toHaveText('0 of 2 done');
  await newCard.fill('Count cottage iris');
  await newCard.press('Enter');
  await page.getByRole('button', { name: 'Start Count cottage iris' }).click();
  await expect(cardsIn('To do')).toHaveCount(0);
  await expect(cardsIn('In progress')).toHaveCount(3);
  await expect(cardsIn('Done')).toHaveCount(0);
  await expect(page.getByTestId('board-summary')).toHaveText('0 of 3 done');
  await page.getByRole('button', { name: 'Finish Count bungalow hazel' }).click();
  await filter.fill('Rest');
  await expect(cardsIn('To do')).toHaveCount(0);
  await expect(cardsIn('In progress')).toHaveCount(1);
  await expect(cardsIn('Done')).toHaveCount(0);
  await expect(page.getByTestId('board-summary')).toHaveText('1 of 3 done');
  await page.reload();
  await expect(cardsIn('To do')).toHaveCount(0);
  await expect(cardsIn('In progress')).toHaveCount(2);
  await expect(cardsIn('Done')).toHaveCount(1);
  await expect(page.getByTestId('board-summary')).toHaveText('1 of 3 done');
});

