import { expect, test } from '@playwright/test';

test('filters, sorts and pages the orders catalog (8 steps)', async ({ page }) => {
  await page.goto('/catalog');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Orders');
  const filter = page.getByRole('searchbox', { name: 'Filter' });
  await page.getByRole('button', { name: /^Price/ }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 140');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('ORD-0032');
  await filter.fill('ord-001');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 10');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await filter.fill('paid');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 27');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await page.getByRole('button', { name: /^Name/ }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 27');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('ORD-0087');
  await page.getByRole('button', { name: 'Next' }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 11-20 of 27');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('ORD-0025');
  await page.getByRole('button', { name: 'Next' }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 21-27 of 27');
  await expect(page.getByTestId('row')).toHaveCount(7);
  await expect(page.getByTestId('row').first()).toContainText('ORD-0104');
  await filter.fill('ord-000');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-9 of 9');
  await expect(page.getByTestId('row')).toHaveCount(9);
  await filter.fill('Rep');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 12');
  await expect(page.getByTestId('row')).toHaveCount(10);
});

test('filters, sorts and pages the orders catalog (5 steps)', async ({ page }) => {
  await page.goto('/catalog');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Orders');
  const filter = page.getByRole('searchbox', { name: 'Filter' });
  await filter.clear();
  await filter.pressSequentially('ord-000');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-9 of 9');
  await expect(page.getByTestId('row')).toHaveCount(9);
  await filter.fill('ORD-0129');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-1 of 1');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await filter.fill('ord-000');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-9 of 9');
  await expect(page.getByTestId('row')).toHaveCount(9);
  await filter.clear();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 140');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('ORD-0001');
  await page.getByRole('button', { name: 'Next' }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 11-20 of 140');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('ORD-0011');
  await page.getByTestId('row').filter({ hasText: 'ORD-0016' }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Store Box');
  await expect(page.getByTestId('detail-price')).toHaveText('$8,983.05');
});

