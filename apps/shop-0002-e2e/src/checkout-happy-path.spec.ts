import { expect, test } from '@playwright/test';

test('validates the checkout form and places an order with items (8 edits)', async ({ page }) => {
  await page.goto('/catalog');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: 'Orders' }).click();
  await page.getByRole('searchbox', { name: 'Filter' }).fill('ORD-0056');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await page.getByTestId('row').first().click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Gift Basket');
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await expect(page.getByTestId('quantity')).toHaveText('3');
  await page.getByRole('button', { name: 'Add to cart' }).click();
  await expect(page.getByRole('status').last()).toHaveText('Added 3 × Gift Basket');
  await expect(page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ })).toHaveText('Cart (3)');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ }).click();
  await page.getByRole('link', { name: 'Proceed to checkout' }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Checkout');
  await page.getByRole('button', { name: 'Place order' }).click();
  await expect(page.getByTestId('error-summary')).toHaveText('7 errors');
  await expect(page.getByRole('alert')).toHaveCount(7);
  await page.getByRole('textbox', { name: 'Full name', exact: true }).clear();
  await page.getByRole('textbox', { name: 'Full name', exact: true }).pressSequentially('Cas Lemmens');
  await expect(page.getByRole('textbox', { name: 'Full name', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Email', exact: true }).fill('ruben.desmet72@example.com');
  await expect(page.getByRole('textbox', { name: 'Email', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Email', exact: true }).clear();
  await page.getByRole('textbox', { name: 'Email', exact: true }).pressSequentially('noor.de.smet77@example.com');
  await expect(page.getByRole('textbox', { name: 'Email', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'City', exact: true }).clear();
  await page.getByRole('textbox', { name: 'City', exact: true }).pressSequentially('Leuven');
  await expect(page.getByRole('textbox', { name: 'City', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Email', exact: true }).fill('bea.hendrickx74@example.com');
  await expect(page.getByRole('textbox', { name: 'Email', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'City', exact: true }).fill('Leuven');
  await expect(page.getByRole('textbox', { name: 'City', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Email', exact: true }).clear();
  await page.getByRole('textbox', { name: 'Email', exact: true }).pressSequentially('lena.lemmens88@example.com');
  await expect(page.getByRole('textbox', { name: 'Email', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('button', { name: 'Place order' }).click();
  await expect(page.getByTestId('error-summary')).toHaveText('4 errors');
  await expect(page.getByRole('alert')).toHaveCount(4);
  await page.getByRole('textbox', { name: 'Address', exact: true }).fill('Main');
  await expect(page.getByRole('textbox', { name: 'Address', exact: true })).toHaveAccessibleDescription('Address must be at least 5 characters');
  await page.getByRole('textbox', { name: 'Address', exact: true }).fill('Gladestraat 77');
  await expect(page.getByRole('textbox', { name: 'Address', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('textbox', { name: 'Postal code', exact: true }).fill('5170');
  await expect(page.getByRole('textbox', { name: 'Postal code', exact: true })).not.toHaveAttribute('aria-invalid');
  await page.getByRole('combobox', { name: 'Delivery' }).selectOption('Express');
  await page.getByRole('checkbox', { name: 'I accept the terms' }).check();
  await page.getByRole('button', { name: 'Place order' }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Thank you, Cas Lemmens');
  await expect(page.getByTestId('order-reference')).toHaveText('REF-0X82IQI');
  await expect(page.getByTestId('order-total')).toHaveText('3 items · $26,873.45');
});

