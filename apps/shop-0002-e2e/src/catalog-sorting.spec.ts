import { expect, test } from '@playwright/test';

test('filters, sorts and pages the orders catalog (9 steps)', async ({ page }) => {
  await page.goto('/catalog');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Orders');
  const filter = page.getByRole('searchbox', { name: 'Filter' });
  await filter.fill('Who');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 14');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await page.getByRole('button', { name: 'Next' }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 11-14 of 14');
  await expect(page.getByTestId('row')).toHaveCount(4);
  await expect(page.getByTestId('row').first()).toContainText('ORD-0108');
  await filter.clear();
  await filter.pressSequentially('ORD-0083');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-1 of 1');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await page.getByRole('button', { name: /^Price/ }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-1 of 1');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await expect(page.getByTestId('row').first()).toContainText('ORD-0083');
  await filter.clear();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 140');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('ORD-0032');
  await page.getByRole('button', { name: /^Name/ }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 140');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('ORD-0058');
  await page.getByRole('button', { name: 'Next' }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 11-20 of 140');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('ORD-0015');
  await page.getByRole('button', { name: 'Next' }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 21-30 of 140');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('ORD-0024');
  await page.getByRole('button', { name: 'Next' }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 31-40 of 140');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('ORD-0027');
  await page.getByTestId('row').filter({ hasText: 'ORD-0123' }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Online Pack');
  await expect(page.getByTestId('detail-price')).toHaveText('$7,489.70');
});

