  await expect(page.getByTestId('row').first()).toContainText('ORD-0057');
  await filter.clear();
  await filter.pressSequentially('refunded');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 34');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await page.getByRole('button', { name: 'Next' }).click();
