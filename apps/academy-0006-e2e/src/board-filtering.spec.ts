import { expect, test } from '@playwright/test';

test('plans work on the board and keeps it after a reload (8 steps)', async ({ page }) => {
  await page.goto('/board');
  const newCard = page.getByRole('textbox', { name: 'New card' });
  const filter = page.getByRole('searchbox', { name: 'Filter cards' });
  const cardsIn = (column: string) => page.getByRole('region', { name: column }).getByTestId('card');
  await newCard.pressSequentially('Call chemistry alpha');
  await newCard.press('Enter');
  await newCard.fill('Restock rhetoric raven');
  await newCard.press('Enter');
  await expect(cardsIn('To do')).toHaveCount(2);
  await expect(cardsIn('In progress')).toHaveCount(0);
  await expect(cardsIn('Done')).toHaveCount(0);
  await expect(page.getByTestId('board-summary')).toHaveText('0 of 2 done');
  await page.getByRole('button', { name: 'Start Call chemistry alpha' }).click();
  await newCard.fill('Email robotics harbor');
  await newCard.press('Enter');
  await expect(cardsIn('To do')).toHaveCount(2);
  await expect(cardsIn('In progress')).toHaveCount(1);
  await expect(cardsIn('Done')).toHaveCount(0);
  await expect(page.getByTestId('board-summary')).toHaveText('0 of 3 done');
  await page.getByRole('button', { name: 'Start Email robotics harbor' }).click();
  await page.getByRole('button', { name: 'Delete Call chemistry alpha' }).click();
  await expect(cardsIn('To do')).toHaveCount(1);
  await expect(cardsIn('In progress')).toHaveCount(1);
  await expect(cardsIn('Done')).toHaveCount(0);
  await expect(page.getByTestId('board-summary')).toHaveText('0 of 2 done');
  await newCard.fill('Count spanish summit');
  await newCard.press('Enter');
  await page.getByRole('button', { name: 'Finish Email robotics harbor' }).click();
  await expect(cardsIn('To do')).toHaveCount(2);
  await expect(cardsIn('In progress')).toHaveCount(0);
  await expect(cardsIn('Done')).toHaveCount(1);
  await expect(page.getByTestId('board-summary')).toHaveText('1 of 3 done');
  await page.reload();
  await expect(cardsIn('To do')).toHaveCount(2);
  await expect(cardsIn('In progress')).toHaveCount(0);
  await expect(cardsIn('Done')).toHaveCount(1);
  await expect(page.getByTestId('board-summary')).toHaveText('1 of 3 done');
});

