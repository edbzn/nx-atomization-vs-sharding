import { expect, test } from '@playwright/test';

test('filters, sorts and pages the courses catalog (7 steps)', async ({ page }) => {
  await page.goto('/catalog');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Courses');
  const filter = page.getByRole('searchbox', { name: 'Filter' });
  await page.getByRole('button', { name: 'Next' }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 11-20 of 64');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('CRS-0011');
  await page.getByRole('button', { name: /^Name/ }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 64');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('CRS-0003');
  await filter.clear();
  await filter.pressSequentially('Han');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-7 of 7');
  await expect(page.getByTestId('row')).toHaveCount(7);
  await filter.clear();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 64');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('CRS-0003');
  await filter.clear();
  await filter.pressSequentially('CRS-0024');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-1 of 1');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await filter.clear();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 64');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('CRS-0003');
  await filter.fill('crs-001');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 10');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await page.getByTestId('row').filter({ hasText: 'CRS-0016' }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Intro Design');
  await expect(page.getByTestId('detail-price')).toHaveText('$5,719.40');
});

