import { expect, test } from '@playwright/test';

test('filters, sorts and pages the courses catalog (6 steps)', async ({ page }) => {
  await page.goto('/catalog');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Courses');
  const filter = page.getByRole('searchbox', { name: 'Filter' });
  await page.getByRole('button', { name: /^Reference/ }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 64');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('CRS-0001');
  await filter.fill('Intr');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-5 of 5');
  await expect(page.getByTestId('row')).toHaveCount(5);
  await page.getByRole('button', { name: /^Name/ }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-5 of 5');
  await expect(page.getByTestId('row')).toHaveCount(5);
  await expect(page.getByTestId('row').first()).toContainText('CRS-0039');
  await page.getByRole('button', { name: /^Name/ }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-5 of 5');
  await expect(page.getByTestId('row')).toHaveCount(5);
  await expect(page.getByTestId('row').first()).toContainText('CRS-0027');
  await filter.fill('CRS-0023');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-1 of 1');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await filter.clear();
  await filter.pressSequentially('spani');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-3 of 3');
  await expect(page.getByTestId('row')).toHaveCount(3);
  await page.getByTestId('row').filter({ hasText: 'CRS-0044' }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Evening Spanish');
  await expect(page.getByTestId('detail-price')).toHaveText('$8,099.17');
});

