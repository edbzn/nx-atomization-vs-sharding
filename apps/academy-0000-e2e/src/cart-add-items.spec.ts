import { expect, test } from '@playwright/test';

test('adds 2 courses to the cart and updates totals', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Academy Portal');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: 'Courses' }).click();
  await page.getByRole('searchbox', { name: 'Filter' }).fill('CRS-0005');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await page.getByTestId('row').first().click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Evening Statistics');
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await expect(page.getByTestId('quantity')).toHaveText('3');
  await page.getByRole('button', { name: 'Add to cart' }).click();
  await expect(page.getByRole('status').last()).toHaveText('Added 3 × Evening Statistics');
  await expect(page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ })).toHaveText('Cart (3)');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: 'Courses' }).click();
  await page.getByRole('searchbox', { name: 'Filter' }).fill('CRS-0015');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await page.getByTestId('row').first().click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Weekend Design');
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await expect(page.getByTestId('quantity')).toHaveText('5');
  await page.getByRole('button', { name: 'Add to cart' }).click();
  await expect(page.getByRole('status').last()).toHaveText('Added 5 × Weekend Design');
  await expect(page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ })).toHaveText('Cart (8)');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ }).click();
  await expect(page.getByTestId('cart-line')).toHaveCount(2);
  await expect(page.getByTestId('line-quantity').nth(0)).toHaveText('3');
  await expect(page.getByTestId('line-total').nth(0)).toHaveText('$4,584.87');
  await expect(page.getByTestId('line-quantity').nth(1)).toHaveText('5');
  await expect(page.getByTestId('line-total').nth(1)).toHaveText('$8,979.40');
  await expect(page.getByTestId('cart-subtotal')).toHaveText('Subtotal: $13,564.27');
  await page.getByRole('button', { name: 'Remove CRS-0005' }).click();
  await expect(page.getByTestId('cart-line')).toHaveCount(1);
  await expect(page.getByTestId('line-quantity').nth(0)).toHaveText('5');
  await expect(page.getByTestId('line-total').nth(0)).toHaveText('$8,979.40');
  await expect(page.getByTestId('cart-subtotal')).toHaveText('Subtotal: $8,979.40');
});

