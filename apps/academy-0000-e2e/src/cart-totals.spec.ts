import { expect, test } from '@playwright/test';

test('adds 3 courses to the cart and updates totals', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Academy Portal');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: 'Courses' }).click();
  await page.getByRole('searchbox', { name: 'Filter' }).fill('CRS-0039');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await page.getByTestId('row').first().click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Intro Botany');
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await expect(page.getByTestId('quantity')).toHaveText('2');
  await page.getByRole('button', { name: 'Add to cart' }).click();
  await expect(page.getByRole('status').last()).toHaveText('Added 2 × Intro Botany');
  await expect(page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ })).toHaveText('Cart (2)');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: 'Courses' }).click();
  await page.getByRole('searchbox', { name: 'Filter' }).fill('CRS-0034');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await page.getByTestId('row').first().click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Evening Welding');
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await expect(page.getByTestId('quantity')).toHaveText('5');
  await page.getByRole('button', { name: 'Add to cart' }).click();
  await expect(page.getByRole('status').last()).toHaveText('Added 5 × Evening Welding');
  await expect(page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ })).toHaveText('Cart (7)');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: 'Courses' }).click();
  await page.getByRole('searchbox', { name: 'Filter' }).fill('CRS-0003');
  await expect(page.getByTestId('row')).toHaveCount(1);
  await page.getByTestId('row').first().click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Visual Robotics');
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await expect(page.getByTestId('quantity')).toHaveText('4');
  await page.getByRole('button', { name: 'Add to cart' }).click();
  await expect(page.getByRole('status').last()).toHaveText('Added 4 × Visual Robotics');
  await expect(page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ })).toHaveText('Cart (11)');
  await page.getByRole('navigation', { name: 'Main' }).getByRole('link', { name: /^Cart/ }).click();
  await expect(page.getByTestId('cart-line')).toHaveCount(3);
  await expect(page.getByTestId('line-quantity').nth(0)).toHaveText('2');
  await expect(page.getByTestId('line-total').nth(0)).toHaveText('$13,524.80');
  await expect(page.getByTestId('line-quantity').nth(1)).toHaveText('5');
  await expect(page.getByTestId('line-total').nth(1)).toHaveText('$34,323.40');
  await expect(page.getByTestId('line-quantity').nth(2)).toHaveText('4');
  await expect(page.getByTestId('line-total').nth(2)).toHaveText('$33,654.88');
  await expect(page.getByTestId('cart-subtotal')).toHaveText('Subtotal: $81,503.08');
  await page.getByRole('button', { name: 'Remove CRS-0034' }).click();
  await expect(page.getByTestId('cart-line')).toHaveCount(2);
  await expect(page.getByTestId('line-quantity').nth(0)).toHaveText('2');
  await expect(page.getByTestId('line-total').nth(0)).toHaveText('$13,524.80');
  await expect(page.getByTestId('line-quantity').nth(1)).toHaveText('4');
  await expect(page.getByTestId('line-total').nth(1)).toHaveText('$33,654.88');
  await expect(page.getByTestId('cart-subtotal')).toHaveText('Subtotal: $47,179.68');
});
