import { expect, test } from '@playwright/test';

test('filters, sorts and pages the courses catalog (6 steps)', async ({ page }) => {
  await page.goto('/catalog');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Courses');
  const filter = page.getByRole('searchbox', { name: 'Filter' });
  await page.getByRole('button', { name: 'Next' }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 11-20 of 64');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('CRS-0011');
  await page.getByRole('button', { name: /^Name/ }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 64');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('CRS-0001');
  await page.getByRole('button', { name: 'Next' }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 11-20 of 64');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('CRS-0044');
  await page.getByRole('button', { name: /^Price/ }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 64');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('CRS-0014');
  await page.getByRole('button', { name: /^Price/ }).click();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 64');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('CRS-0048');
  await filter.clear();
  await filter.pressSequentially('chemis');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-3 of 3');
  await expect(page.getByTestId('row')).toHaveCount(3);
});

test('filters, sorts and pages the courses catalog (3 steps)', async ({ page }) => {
  await page.goto('/catalog');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Courses');
  const filter = page.getByRole('searchbox', { name: 'Filter' });
  await filter.fill('Eve');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-9 of 9');
  await expect(page.getByTestId('row')).toHaveCount(9);
  await filter.clear();
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 64');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await expect(page.getByTestId('row').first()).toContainText('CRS-0001');
  await filter.fill('crs-001');
  await expect(page.getByTestId('table-status')).toHaveText('Showing 1-10 of 10');
  await expect(page.getByTestId('row')).toHaveCount(10);
  await page.getByTestId('row').filter({ hasText: 'CRS-0015' }).click();
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Weekend Design');
  await expect(page.getByTestId('detail-price')).toHaveText('$1,795.88');
});

