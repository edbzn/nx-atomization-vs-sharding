    await user.click(screen.getByRole('button', { name: 'Create campaign' }));
    expect(onComplete).toHaveBeenCalledExactlyOnceWith({"name":"Winter Promo","category":"Display","tags":["sage83","onyx-cobalt","garnet","reef-drift","frost-prism"]});
    expect(screen.getByRole('status')).toHaveTextContent('Created Winter Promo');
