    expect(screen.getByTestId('tag-count').textContent).toBe('2 tags');
    expect(screen.queryAllByTestId('tag')).toHaveLength(2);
    expect(screen.getByTestId('tag-message').textContent).toBe('"comet-velvet" is already added');
    await user.type(tagInput(), 'nova53{Enter}');
