import { render, screen } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { describe, expect, it, vi } from 'vitest';
import { RecipeForm } from './RecipeForm';

describe('RecipeForm editing', () => {
  it('validates and saves a recipe (6 interactions)', async () => {
    const onSubmit = vi.fn();
    const user = userEvent.setup();
    render(<RecipeForm onSubmit={onSubmit} />);
    await user.clear(screen.getByRole('textbox', { name: 'Notes' }));
    await user.type(screen.getByRole('textbox', { name: 'Notes' }), 'umber zephyr quartz vale indigo maple glade prism ember mesa harbor garnet comet coral tundra topaz prism iris sable flint pine zinc solstice coral coral meadow lumen nova reef blaze onyx cobalt hazel ');
    expect(screen.getByRole('textbox', { name: 'Notes' })).not.toHaveAttribute('aria-invalid');
    await user.clear(screen.getByRole('textbox', { name: 'Name' }));
    await user.type(screen.getByRole('textbox', { name: 'Name' }), 'Herbed Risotto 73');
    expect(screen.getByRole('textbox', { name: 'Name' })).not.toHaveAttribute('aria-invalid');
    await user.clear(screen.getByRole('textbox', { name: 'Email' }));
    await user.type(screen.getByRole('textbox', { name: 'Email' }), 'wout.hendrickx68@example.com');
    expect(screen.getByRole('textbox', { name: 'Email' })).not.toHaveAttribute('aria-invalid');
    await user.clear(screen.getByRole('textbox', { name: 'Amount' }));
    await user.type(screen.getByRole('textbox', { name: 'Amount' }), '19094');
    expect(screen.getByRole('textbox', { name: 'Amount' })).not.toHaveAttribute('aria-invalid');
    await user.selectOptions(screen.getByRole('combobox', { name: 'Category' }), 'Starter');
    expect(screen.getByRole('combobox', { name: 'Category' })).not.toHaveAttribute('aria-invalid');
    await user.click(screen.getByRole('button', { name: 'Save recipe' }));
    expect(onSubmit).toHaveBeenCalledTimes(1);
    expect(onSubmit).toHaveBeenLastCalledWith({"name":"Herbed Risotto 73","email":"wout.hendrickx68@example.com","category":"Starter","amount":19094,"notes":"umber zephyr quartz vale indigo maple glade prism ember mesa harbor garnet comet coral tundra topaz prism iris sable flint pine zinc solstice coral coral meadow lumen nova reef blaze onyx cobalt hazel "});
    expect(screen.queryByTestId('error-summary')).not.toBeInTheDocument();
  });
});
