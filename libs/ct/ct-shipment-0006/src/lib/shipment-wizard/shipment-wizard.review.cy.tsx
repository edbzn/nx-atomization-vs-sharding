import { ShipmentWizard } from './ShipmentWizard';

describe('ShipmentWizard review', () => {
  it('creates a shipment in three steps with 6 tags', () => {
    const onComplete = cy.stub().as('complete');
    cy.mount(<ShipmentWizard onComplete={onComplete} />);
    cy.get('[data-testid=wizard-step]').should('have.text', 'Step 1 of 3: Details');
    cy.contains('button', 'Next').click();
    cy.contains('[role=alert]', 'Name is required').should('be.visible');
    cy.contains('[role=alert]', 'Category is required').should('be.visible');
    cy.get('[data-testid=wizard-step]').should('have.text', 'Step 1 of 3: Details');
    cy.get('input[name=wizard-name]').clear().type('Zoe Cools');
    cy.get('select[name=wizard-category]').select('Returned');
    cy.contains('button', 'Next').click();
    cy.get('[data-testid=wizard-step]').should('have.text', 'Step 2 of 3: Tags');
    cy.get('input[name=new-tag]').type('willow68{enter}');
    cy.get('[data-testid=tag-count]').should('have.text', '1 tag');
    cy.get('[data-testid=tag]').should('have.length', 1);
    cy.get('[data-testid=tag-message]').should('not.exist');
    cy.get('input[name=new-tag]').type('prism{enter}');
    cy.get('[data-testid=tag-count]').should('have.text', '2 tags');
    cy.get('[data-testid=tag]').should('have.length', 2);
    cy.get('[data-testid=tag-message]').should('not.exist');
    cy.get('input[name=new-tag]').type('  prism {enter}');
    cy.get('[data-testid=tag-count]').should('have.text', '2 tags');
    cy.get('[data-testid=tag]').should('have.length', 2);
    cy.get('[data-testid=tag-message]').should('have.text', '"prism" is already added');
    cy.get('input[name=new-tag]').type('IRIS{enter}');
    cy.get('[data-testid=tag-count]').should('have.text', '3 tags');
    cy.get('[data-testid=tag]').should('have.length', 3);
    cy.get('[data-testid=tag-message]').should('not.exist');
    cy.get('input[name=new-tag]').type('glade47{enter}');
    cy.get('[data-testid=tag-count]').should('have.text', '4 tags');
    cy.get('[data-testid=tag]').should('have.length', 4);
    cy.get('[data-testid=tag-message]').should('not.exist');
    cy.get('input[name=new-tag]').type('iris river{enter}');
    cy.get('[data-testid=tag-count]').should('have.text', '5 tags');
    cy.get('[data-testid=tag]').should('have.length', 5);
    cy.get('[data-testid=tag-message]').should('not.exist');
    cy.get('input[name=new-tag]').type('ridge61{enter}');
    cy.get('[data-testid=tag-count]').should('have.text', '6 tags');
    cy.get('[data-testid=tag]').should('have.length', 6);
    cy.get('[data-testid=tag-message]').should('not.exist');
    cy.get('input[name=new-tag]').type('GLADE47{enter}');
    cy.get('[data-testid=tag-count]').should('have.text', '6 tags');
    cy.get('[data-testid=tag]').should('have.length', 6);
    cy.get('[data-testid=tag-message]').should('have.text', '"glade47" is already added');
    cy.contains('button', 'Back').click();
    cy.get('input[name=wizard-name]').should('have.value', 'Zoe Cools');
    cy.contains('button', 'Next').click();
    cy.get('[data-testid=tag]').should('have.length', 6);
    cy.contains('button', 'Next').click();
    cy.get('[data-testid=review-name]').should('have.text', 'Zoe Cools');
    cy.get('[data-testid=review-category]').should('have.text', 'Returned');
    cy.get('[data-testid=review-tags]').should('have.text', 'willow68, prism, iris, glade47, iris-river, ridge61');
    cy.contains('button', 'Create shipment').click();
    cy.get('@complete').should('have.been.calledOnceWith', {"name":"Zoe Cools","category":"Returned","tags":["willow68","prism","iris","glade47","iris-river","ridge61"]});
    cy.contains('[role=status]', 'Created Zoe Cools').should('be.visible');
  });
});
