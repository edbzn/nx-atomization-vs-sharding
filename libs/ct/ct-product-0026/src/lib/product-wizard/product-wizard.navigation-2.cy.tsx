    cy.get('[data-testid=review-name]').should('have.text', 'Brushed Stool');
    cy.get('[data-testid=review-category]').should('have.text', 'Office');
    cy.get('[data-testid=review-tags]').should('have.text', 'delta54, drift, vale26');
