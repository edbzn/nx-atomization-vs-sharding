    cy.get('[data-testid=tag-message]').should('not.exist');
    cy.get('input[name=new-tag]').type('LAGOON{enter}');
    cy.get('[data-testid=tag-count]').should('have.text', '2 tags');
    cy.get('[data-testid=tag]').should('have.length', 2);
    cy.get('[data-testid=tag-message]').should('not.exist');
    cy.get('input[name=new-tag]').type('atlas{enter}');
    cy.get('[data-testid=tag-count]').should('have.text', '3 tags');
    cy.get('[data-testid=tag]').should('have.length', 3);
    cy.get('[data-testid=tag-message]').should('not.exist');
    cy.contains('button', 'Next').click();
    cy.get('[data-testid=review-name]').should('have.text', 'Noor Lemmens');
    cy.get('[data-testid=review-category]').should('have.text', 'Bug');
    cy.get('[data-testid=review-tags]').should('have.text', 'falcon-iris, lagoon, atlas');
    cy.contains('button', 'Create ticket').click();
    cy.get('@complete').should('have.been.calledOnceWith', {"name":"Noor Lemmens","category":"Bug","tags":["falcon-iris","lagoon","atlas"]});
    cy.contains('[role=status]', 'Created Noor Lemmens').should('be.visible');
