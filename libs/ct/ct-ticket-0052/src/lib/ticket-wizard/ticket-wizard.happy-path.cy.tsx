    cy.get('[data-testid=tag]').should('have.length', 6);
    cy.get('[data-testid=tag-message]').should('not.exist');
    cy.get('button[aria-label="Remove birch"]').click();
    cy.get('[data-testid=tag-count]').should('have.text', '5 tags');
    cy.get('[data-testid=tag]').should('have.length', 5);
    cy.get('[data-testid=tag-message]').should('not.exist');
    cy.get('input[name=new-tag]').type('tide{enter}');
    cy.get('[data-testid=tag-count]').should('have.text', '6 tags');
    cy.get('[data-testid=tag]').should('have.length', 6);
    cy.get('[data-testid=tag-message]').should('not.exist');
    cy.contains('button', 'Back').click();
    cy.get('input[name=wizard-name]').should('have.value', 'Stuck Payment');
    cy.contains('button', 'Next').click();
    cy.get('[data-testid=tag]').should('have.length', 6);
    cy.contains('button', 'Next').click();
    cy.get('[data-testid=review-name]').should('have.text', 'Stuck Payment');
    cy.get('[data-testid=review-category]').should('have.text', 'Question');
    cy.get('[data-testid=review-tags]').should('have.text', 'raven-alpha, velvet, garnet, juniper, frost66, tide');
    cy.contains('button', 'Create ticket').click();
    cy.get('@complete').should('have.been.calledOnceWith', {"name":"Stuck Payment","category":"Question","tags":["raven-alpha","velvet","garnet","juniper","frost66","tide"]});
    cy.contains('[role=status]', 'Created Stuck Payment').should('be.visible');
